-- ---------- 1. Bảng sản phẩm ----------
create table if not exists san_pham (
  id             bigint generated by default as identity primary key,
  ten            text not null,
  nhom           text not null check (nhom in ('cua-sat','cua-nhom','nha-panel','tu-bep','mai-che','bao-tri')),
  mo_ta_ngan     text,
  mo_ta_chi_tiet text,
  vat_lieu       text,
  uu_diem        text,
  bao_hanh       text default 'Bảo hành theo chính sách công ty, hỗ trợ sửa chữa nhanh khi khách cần',
  gia            text not null default 'Liên hệ',
  hinh_anh       text,
  noi_bat        boolean not null default false,
  thu_tu         int not null default 0,
  created_at     timestamptz not null default now()
);

-- ---------- 2. Bảng yêu cầu báo giá (từ giỏ) ----------
create table if not exists yeu_cau_bao_gia (
  id             bigint generated by default as identity primary key,
  ho_ten         text not null check (length(trim(ho_ten)) > 0),
  so_dien_thoai  text not null check (so_dien_thoai ~ '^0[0-9]{9}$'),
  email          text,
  dia_chi        text,
  ghi_chu        text,
  danh_sach      jsonb not null check (jsonb_typeof(danh_sach) = 'array' and jsonb_array_length(danh_sach) > 0),
  trang_thai     text not null default 'moi' check (trang_thai in ('moi','da_lien_he','da_bao_gia','hoan_tat')),
  created_at     timestamptz not null default now()
);

-- ---------- 3. Bảng thiết kế nhà panel 3D gửi báo giá ----------
create table if not exists thiet_ke_nha (
  id             bigint generated by default as identity primary key,
  ma_thiet_ke    text not null unique,
  ho_ten         text not null check (length(trim(ho_ten)) > 0),
  so_dien_thoai  text not null check (so_dien_thoai ~ '^0[0-9]{9}$'),
  dia_chi        text,
  ghi_chu        text,
  cau_hinh       jsonb not null,   -- toàn bộ tùy chọn khách chọn
  ket_qua        jsonb,            -- diện tích, số tấm panel... đã tính
  trang_thai     text not null default 'moi' check (trang_thai in ('moi','da_lien_he','da_bao_gia','hoan_tat')),
  created_at     timestamptz not null default now()
);

-- ---------- 4. Bảng lịch khảo sát & công trình ----------
create table if not exists lich_khao_sat (
  id                 bigint generated by default as identity primary key,
  ma_lich            text not null unique,
  ho_ten             text not null,
  so_dien_thoai      text not null check (so_dien_thoai ~ '^0[0-9]{9}$'),
  dia_chi_cong_trinh text not null,
  dich_vu            text,
  ngay_hen           date not null,
  buoi               text not null default 'sang' check (buoi in ('sang','chieu')),
  ghi_chu            text,
  trang_thai         text not null default 'cho_xac_nhan',
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
-- Các bước tiến độ (cập nhật ràng buộc để chạy lại an toàn)
alter table lich_khao_sat drop constraint if exists lich_khao_sat_trang_thai_check;
alter table lich_khao_sat add constraint lich_khao_sat_trang_thai_check check (trang_thai in
  ('cho_xac_nhan','da_xac_nhan','da_khao_sat','da_bao_gia','dang_gia_cong','dang_lap_dat','hoan_thanh','da_huy'));

-- ---------- 5. Bảng nhật ký tiến độ công trình ----------
create table if not exists tien_do (
  id          bigint generated by default as identity primary key,
  lich_id     bigint not null references lich_khao_sat(id) on delete cascade,
  buoc        text not null check (buoc in
               ('cho_xac_nhan','da_xac_nhan','da_khao_sat','da_bao_gia','dang_gia_cong','dang_lap_dat','hoan_thanh','da_huy')),
  ghi_chu     text,
  created_at  timestamptz not null default now()
);

-- ---------- 6. Bảng công trình đã thi công (bản đồ) ----------
create table if not exists cong_trinh (
  id          bigint generated by default as identity primary key,
  ten         text not null,
  hang_muc    text not null check (hang_muc in ('cua-sat','cua-nhom','nha-panel','tu-bep','mai-che','bao-tri')),
  dia_diem    text not null,
  vi_do       double precision not null,   -- latitude
  kinh_do     double precision not null,   -- longitude
  nam         int,
  mo_ta       text,
  hinh_anh    text,
  thu_tu      int not null default 0,
  created_at  timestamptz not null default now()
);

-- ---------- 7. Bảng đánh giá khách hàng ----------
create table if not exists danh_gia (
  id            bigint generated by default as identity primary key,
  ho_ten        text not null check (length(trim(ho_ten)) > 0),
  so_sao        int  not null check (so_sao between 1 and 5),
  noi_dung      text not null check (length(trim(noi_dung)) >= 10),
  dich_vu       text,              -- mã nhóm hoặc tên công trình khách chọn (không bắt buộc)
  da_duyet      boolean not null default false,
  created_at    timestamptz not null default now()
);

-- ---------- 7a. Bảng bài viết / tin tức (3 ngôn ngữ) ----------
create table if not exists bai_viet (
  id            bigint generated by default as identity primary key,
  slug          text not null unique check (slug ~ '^[a-z0-9-]+$'),  -- đường dẫn không dấu, vd nha-panel-eps-hay-pu
  chuyen_muc    text not null default 'kien-thuc' check (chuyen_muc in ('kien-thuc','tin-cong-ty','cong-trinh')),
  tieu_de       text not null,  tieu_de_en  text,  tieu_de_zh  text,
  tom_tat       text,           tom_tat_en  text,  tom_tat_zh  text,
  noi_dung      text not null,  noi_dung_en text,  noi_dung_zh text,   -- viết bằng Markdown
  anh_dai_dien  text,           -- đường dẫn ảnh (assets/images/... hoặc link Supabase Storage)
  da_dang       boolean not null default false,  -- false = bản nháp, khách không thấy
  noi_bat       boolean not null default false,
  luot_xem      int not null default 0,
  ngay_dang     date not null default current_date,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

