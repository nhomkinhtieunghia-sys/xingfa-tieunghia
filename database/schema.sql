-- 10.1 Đặt lịch mới → trả về mã lịch (vd TN-4821) + ghi bước tiến độ đầu tiên
create or replace function dat_lich_khao_sat(
  p_ho_ten text, p_so_dien_thoai text, p_dia_chi text, p_dich_vu text,
  p_ngay_hen date, p_buoi text, p_ghi_chu text default null, p_ngon_ngu text default 'vi'
) returns text
language plpgsql security definer set search_path = public as $$
declare v_ma text; v_id bigint;
begin
  if p_ngay_hen < current_date then
    raise exception 'Ngày hẹn không được ở quá khứ';
  end if;
  loop
    v_ma := 'TN-' || lpad((floor(random() * 10000))::int::text, 4, '0');
    exit when not exists (select 1 from lich_khao_sat where ma_lich = v_ma);
  end loop;
  insert into lich_khao_sat (ma_lich, ho_ten, so_dien_thoai, dia_chi_cong_trinh, dich_vu, ngay_hen, buoi, ghi_chu, ngon_ngu)
  values (v_ma, trim(p_ho_ten), trim(p_so_dien_thoai), trim(p_dia_chi), p_dich_vu, p_ngay_hen, coalesce(p_buoi, 'sang'), p_ghi_chu, coalesce(p_ngon_ngu, 'vi'))
  returning id into v_id;
  insert into tien_do (lich_id, buoc, ghi_chu) values (v_id, 'cho_xac_nhan', 'Khách đặt lịch khảo sát qua website');
  return v_ma;
end; $$;

-- 10.2 Tra cứu lịch + toàn bộ tiến độ (phải đúng cả mã lịch + SĐT). Không tìm thấy → null
create or replace function tra_cuu_lich(p_ma_lich text, p_so_dien_thoai text)
returns json
language plpgsql security definer set search_path = public as $$
declare v json;
begin
  select json_build_object(
           'lich', to_jsonb(l),
           'tien_do', coalesce((
              select json_agg(json_build_object('buoc', t.buoc, 'ghi_chu', t.ghi_chu, 'thoi_gian', t.created_at)
                              order by t.created_at)
              from tien_do t where t.lich_id = l.id), '[]'::json))
    into v
    from lich_khao_sat l
   where l.ma_lich = upper(trim(p_ma_lich)) and l.so_dien_thoai = trim(p_so_dien_thoai);
  return v;
end; $$;

-- 10.3 Đổi ngày / buổi hẹn (chỉ khi chưa khảo sát) → true nếu đổi được
create or replace function doi_lich(
  p_ma_lich text, p_so_dien_thoai text, p_ngay_hen date, p_buoi text, p_ghi_chu text default null
) returns boolean
language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  if p_ngay_hen < current_date then
    raise exception 'Ngày hẹn không được ở quá khứ';
  end if;
  update lich_khao_sat
     set ngay_hen = p_ngay_hen, buoi = coalesce(p_buoi, buoi), ghi_chu = coalesce(p_ghi_chu, ghi_chu),
         trang_thai = 'cho_xac_nhan', updated_at = now()
   where ma_lich = upper(trim(p_ma_lich)) and so_dien_thoai = trim(p_so_dien_thoai)
     and trang_thai in ('cho_xac_nhan','da_xac_nhan')
  returning id into v_id;
  if v_id is null then return false; end if;
  insert into tien_do (lich_id, buoc, ghi_chu)
  values (v_id, 'cho_xac_nhan', 'Khách đổi lịch sang ' || to_char(p_ngay_hen, 'DD/MM/YYYY')
                               || case when p_buoi = 'chieu' then ' (buổi chiều)' else ' (buổi sáng)' end);
  return true;
end; $$;

-- 10.4 Hủy lịch (chỉ khi chưa khảo sát) → true nếu hủy được
create or replace function huy_lich(p_ma_lich text, p_so_dien_thoai text)
returns boolean
language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  update lich_khao_sat set trang_thai = 'da_huy', updated_at = now()
   where ma_lich = upper(trim(p_ma_lich)) and so_dien_thoai = trim(p_so_dien_thoai)
     and trang_thai in ('cho_xac_nhan','da_xac_nhan')
  returning id into v_id;
  if v_id is null then return false; end if;
  insert into tien_do (lich_id, buoc, ghi_chu) values (v_id, 'da_huy', 'Khách hủy lịch qua website');
  return true;
end; $$;

-- 10.5 Gửi thiết kế nhà panel 3D → trả về mã thiết kế (vd TK-04821)
create or replace function gui_thiet_ke_nha(
  p_ho_ten text, p_so_dien_thoai text, p_dia_chi text, p_ghi_chu text,
  p_cau_hinh jsonb, p_ket_qua jsonb, p_ngon_ngu text default 'vi'
) returns text
language plpgsql security definer set search_path = public as $$
declare v_ma text;
begin
  loop
    v_ma := 'TK-' || lpad((floor(random() * 100000))::int::text, 5, '0');
    exit when not exists (select 1 from thiet_ke_nha where ma_thiet_ke = v_ma);
  end loop;
  insert into thiet_ke_nha (ma_thiet_ke, ho_ten, so_dien_thoai, dia_chi, ghi_chu, cau_hinh, ket_qua, ngon_ngu)
  values (v_ma, trim(p_ho_ten), trim(p_so_dien_thoai), p_dia_chi, p_ghi_chu, p_cau_hinh, p_ket_qua, coalesce(p_ngon_ngu, 'vi'));
  return v_ma;
end; $$;

-- 10.6 Tăng lượt xem bài viết (khách không có quyền UPDATE trực tiếp)
create or replace function tang_luot_xem(p_slug text)
returns void
language sql security definer set search_path = public as $$
  update bai_viet set luot_xem = luot_xem + 1 where slug = p_slug and da_dang = true;
$$;

